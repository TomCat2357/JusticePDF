def normalize_theme_id(value) -> str:
    """設定値をテーマ ID へ。廃止 ID は読み替え、未知・不正な値は標準へ戻す。"""
    if isinstance(value, str):
        value = ALIASES.get(value, value)
        if value in THEME_IDS:
            return value
    return DEFAULT_THEME


