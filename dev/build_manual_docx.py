def main() -> None:
    doc = build_doc()
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT_DOCX))
    print(f"saved: {OUT_DOCX}")


if __name__ == "__main__":
    main()
